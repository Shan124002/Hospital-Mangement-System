    public void refreshTable() {
    DefaultTableModel model = (javax.swing.table.DefaultTableModel) ratesTB.getModel(); 
    model.setRowCount(0); 
    ArrayList<String[]> data = TableManager.getPrices();
    
    for (int i = 0; i < data.size(); i++) {
        model.addRow(data.get(i));
    }
}
    
