    private void ratesTBMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_ratesTBMouseClicked
        // TODO add your handling code here:
        int selectedRow = ratesTB.getSelectedRow();
        if (selectedRow != -1) {
        String type = ratesTB.getValueAt(selectedRow, 0).toString();
        String rate = ratesTB.getValueAt(selectedRow, 1).toString();
    
        consultationTypeCB.setSelectedItem(type); 
        rateTF.setText(rate);                    
        }
    }//GEN-LAST:event_ratesTBMouseClicked

    private void updateBTActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBTActionPerformed
        // TODO add your handling code here:
        String selectedType = consultationTypeCB.getSelectedItem().toString();

        if (selectedType.equals("Select Consultation")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please select a valid Consultation Type from the list!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (rateTF.getText().trim().isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Please enter a valid rate!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        String rate = rateTF.getText().trim();
        AdminStaff admin = new AdminStaff();
        boolean success = admin.updatePrice(selectedType, rate);

        if (success) {
            javax.swing.JOptionPane.showMessageDialog(this, "Consultation Rate Updated Successfully!");
        } else {
            javax.swing.JOptionPane.showMessageDialog(this, "Failed to update rate.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
        
        
        rateTF.setText("");
        consultationTypeCB.setSelectedIndex(0);
        refreshTable(); 
    }//GEN-LAST:event_updateBTActionPerformed

