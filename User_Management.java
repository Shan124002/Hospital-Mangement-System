    private void updateBTActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_updateBTActionPerformed
        // TODO add your handling code here:
        
        if (roleCB.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Please select a valid role from the list!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return; 
        }
        
        String id = useridTF.getText(); 
        String name = nameTF.getText();
        String pass = passwordPF.getText();
        String role = roleCB.getSelectedItem().toString(); 
        String email = emailTF.getText();
        String phone = phoneTF.getText();

    AdminStaff admin = new AdminStaff();
    boolean success = admin.updateUser(id, name, pass, role, email, phone);

    if (success) {
        javax.swing.JOptionPane.showMessageDialog(this, "User Updated Successfully!");
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Failed to update user.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    
       useridTF.setText("");
       nameTF.setText("");
       passwordPF.setText("");
       roleCB.setSelectedItem("Select role");
       emailTF.setText("");
       phoneTF.setText("");
       refreshTable();
    }//GEN-LAST:event_updateBTActionPerformed

