    private void addBTActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addBTActionPerformed
        // TODO add your handling code here:
        
        if (roleCB.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Please select a valid role from the list!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return; 
        }
        
        String id = useridTF.getText(); 
        String name = nameTF.getText();
        String pass = passwordPF.getText();
        String role = roleCB.getSelectedItem().toString(); 
        String email = emailTF.getText();
        String phone = phoneTF.getText();
        
        
        
        AdminStaff admin = new AdminStaff();
        boolean success = admin.createUser(id, name, pass, role, email, phone);
        
        if (success) {
                JOptionPane.showMessageDialog(this, "User Add Successfully!");
            } else {
                JOptionPane.showMessageDialog(this, "Error adding User!");
            }
        
       useridTF.setText("");
       nameTF.setText("");
       passwordPF.setText("");
       roleCB.setSelectedItem("Select role");
       emailTF.setText("");
       phoneTF.setText("");
       refreshTable();
    }//GEN-LAST:event_addBTActionPerformed

    private void deletBTActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_deletBTActionPerformed
        // TODO add your handling code here:
        
        if (roleCB.getSelectedIndex() == 0) {
            JOptionPane.showMessageDialog(this, "Please select a valid role from the list!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return; 
        }
        
        String targetId = useridTF.getText(); 
        String role = roleCB.getSelectedItem().toString();

        int confirm = JOptionPane.showConfirmDialog(this, "Are you sure you want to delete this user?", "Confirm Delete", JOptionPane.YES_NO_OPTION);

        if (confirm == javax.swing.JOptionPane.YES_OPTION) {
            AdminStaff admin = new AdminStaff();
            boolean success = admin.deleteUser(targetId, role);

            if (success) {
                JOptionPane.showMessageDialog(this, "User Deleted Successfully!");
            } else {
                JOptionPane.showMessageDialog(this, "Error Deleting User!");
            }
        }
        
       useridTF.setText("");
       nameTF.setText("");
       passwordPF.setText("");
       roleCB.setSelectedItem("Select role");
       emailTF.setText("");
       phoneTF.setText("");
       refreshTable();
    }//GEN-LAST:event_deletBTActionPerformed

    private void usersTBMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_usersTBMouseClicked
        // TODO add your handling code here:
        int selectedRow = usersTB.getSelectedRow();

        if (selectedRow != -1) {
            javax.swing.table.DefaultTableModel model = (DefaultTableModel) usersTB.getModel();
            useridTF.setText(model.getValueAt(selectedRow, 0).toString());
            nameTF.setText(model.getValueAt(selectedRow, 1).toString());
            passwordPF.setText(model.getValueAt(selectedRow, 2).toString());
            roleCB.setSelectedItem(model.getValueAt(selectedRow, 5).toString());
            emailTF.setText(model.getValueAt(selectedRow, 4).toString());
            phoneTF.setText(model.getValueAt(selectedRow, 3).toString());
            }
    }//GEN-LAST:event_usersTBMouseClicked

    private void filterCBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_filterCBActionPerformed
        // TODO add your handling code here:
        String selectedRole = filterCB.getSelectedItem().toString();

        DefaultTableModel model = (DefaultTableModel) usersTB.getModel();

        TableRowSorter<javax.swing.table.DefaultTableModel> sorter = new javax.swing.table.TableRowSorter<>(model);
        usersTB.setRowSorter(sorter);

        if (selectedRole.equals("All")) {
            sorter.setRowFilter(null); 
        } else {
            sorter.setRowFilter(RowFilter.regexFilter("^" + selectedRole + "$", 5));
        }
    }//GEN-LAST:event_filterCBActionPerformed
    
public void refreshTable() {
    DefaultTableModel model = (DefaultTableModel) usersTB.getModel();
    model.setRowCount(0); 
    
    ArrayList<String[]> usersData = TableManager.getAllUsers();
    for (int i = 0; i < usersData.size(); i++) {
        String[] row = usersData.get(i);
        model.addRow(row);
    }
    
}    
