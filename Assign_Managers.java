    private void removeBTActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_removeBTActionPerformed
        int selectedRow = doctorsTB.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a doctor from the table first!", "Warning", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }
        
        String doctorId = doctorsTB.getValueAt(selectedRow, 0).toString();
        
        int confirm = JOptionPane.showConfirmDialog(this, 
            "Are you sure you want to remove the manager from this doctor?", 
            "Confirm Removal", 
            JOptionPane.YES_NO_OPTION);

        if (confirm == JOptionPane.YES_OPTION) {

            AdminStaff admin = new AdminStaff();
            boolean success = admin.assignManager(doctorId, "Unassigned");

            if (success) {
                JOptionPane.showMessageDialog(this, "Manager Removed Successfully!");

                managerTF.setText("");
            } else {
                JOptionPane.showMessageDialog(this, "Failed to remove manager.", "Error", JOptionPane.ERROR_MESSAGE);
            }
            
            refreshTable();
        }
        
        doctorIdTF.setText("");
        doctorNameTF.setText("");
        managerTF.setText("");
        
        
        refreshTable();
    }//GEN-LAST:event_removeBTActionPerformed

    private void doctorsTBMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_doctorsTBMouseClicked
        // TODO add your handling code here:
        int selectedRow = doctorsTB.getSelectedRow();

        if (selectedRow != -1) {
        
        String doctorId = doctorsTB.getValueAt(selectedRow, 0).toString();
        String doctorName = doctorsTB.getValueAt(selectedRow, 1).toString();
        String currentManager = doctorsTB.getValueAt(selectedRow, 2).toString();
        
        doctorIdTF.setText(doctorId);
        doctorNameTF.setText(doctorName);
        
        if (currentManager.equals("Unassigned_Manager")) {
            managerTF.setText("");
        } else {
            managerTF.setText(currentManager);
        }
}
    }//GEN-LAST:event_doctorsTBMouseClicked

    private void filterCBActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_filterCBActionPerformed
        // TODO add your handling code here:
        String selectedFilter = filterCB.getSelectedItem().toString();

        DefaultTableModel model = (javax.swing.table.DefaultTableModel) doctorsTB.getModel();

        TableRowSorter<javax.swing.table.DefaultTableModel> sorter = new TableRowSorter<>(model);
        doctorsTB.setRowSorter(sorter);

        if (selectedFilter.equals("All")) {
            sorter.setRowFilter(null); 
        } else if (selectedFilter.equals("Unassigned")) {
            sorter.setRowFilter(javax.swing.RowFilter.regexFilter("^Unassigned$", 2));
        }
    }//GEN-LAST:event_filterCBActionPerformed
    
    public void refreshTable() {
        javax.swing.table.DefaultTableModel model = (javax.swing.table.DefaultTableModel) doctorsTB.getModel();
        model.setRowCount(0); 
    
        ArrayList<String[]> doctorsData = TableManager.getDoctorsAndManagers();
    
        for (int i = 0; i < doctorsData.size(); i++) {
            String[] row = doctorsData.get(i);
            model.addRow(row);
        }
    
}  
    
