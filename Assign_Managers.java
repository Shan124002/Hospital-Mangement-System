    private void assignBTActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_assignBTActionPerformed
        // TODO add your handling code here:
        int selectedRow = doctorsTB.getSelectedRow();
        if (selectedRow == -1) {
            JOptionPane.showMessageDialog(this, "Please select a doctor from the table first!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }

        
        if (managerTF.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Please select a valid manager from the list!", "Warning", JOptionPane.WARNING_MESSAGE);
            return;
        }


        String doctorId = doctorsTB.getValueAt(selectedRow, 0).toString();
        String managerName = managerTF.getText().toString();
        AdminStaff admin = new AdminStaff();
        
        if (!admin.checkManager(managerName)) {
        JOptionPane.showMessageDialog(this, "Manager name not found in the system! Please check the spelling.", "Error",JOptionPane.ERROR_MESSAGE);
        return;
    }
        
        boolean success = admin.assignManager(doctorId, managerName);

        if (success) {
            JOptionPane.showMessageDialog(this, "Manager Assigned Successfully!");
        } else {
            JOptionPane.showMessageDialog(this, "Failed to assign manager.", "Error", JOptionPane.ERROR_MESSAGE);
        }
        
        doctorIdTF.setText("");
        doctorNameTF.setText("");
        managerTF.setText("");
        
        refreshTable();
        
    }//GEN-LAST:event_assignBTActionPerformed

